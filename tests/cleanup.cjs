const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { Store, validateSettings } = require('../electron/config.cjs');
const { createCleanup } = require('../electron/cleanup.cjs');

(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'agentc2-cleanup-state-'));
  try {
    const store = new Store(directory);
    const events = new EventEmitter();
    const id = 'fixture-old', key = `default/claude:${id}`;
    let remoteCalls = 0, deletes = 0, outcome = 'deleted', providerPinned = false, activity = '2020-01-01T00:00:00Z', rejectPreview = false;
    let pauseDelete;
    const settings = { ...store.data.settings, cleanup: [{ hostId: 'default', provider: 'claude', enabled: false, days: 30 }] };
    store.save('settings', validateSettings(settings));
    let sessions = [{ key, id, title: 'Old fixture', hostId: 'default', provider: 'claude', kind: 'conversation', updatedAt: activity }];
    const inventory = async () => ({ hosts: [{ id: 'default', connected: true }], sessions });
    const runRemote = async (payload) => {
      remoteCalls++;
      if (payload.action === 'cleanup_preview') {
        if (rejectPreview) throw new Error('Offline fixture');
        return { items: payload.ids.map((value) => ({ id: value, provider: 'claude', eligible: true, reason: '', fingerprint: 'fixture-hash', updatedAt: activity, bytes: 12, files: ['.claude/projects/fixture.jsonl'], providerPinned })) };
      }
      assert.equal(payload.action, 'cleanup_delete');
      deletes++;
      if (pauseDelete) await pauseDelete;
      if (outcome === 'unknown') throw new Error('SSH timed out');
      if (outcome === 'deleted') sessions = [];
      return { items: payload.items.map((item) => ({ id: item.id, status: outcome, detail: 'Fixture result', bytes: 12 })) };
    };
    const options = { store, events, inventory, runRemote, hostId: (value) => { if (value !== 'default') throw new Error('Unknown host'); return value; } };
    const cleanup = createCleanup(options);
    for (const policy of [{ ...settings.cleanup[0], days: 0 }, { ...settings.cleanup[0], days: 1.5 }, { ...settings.cleanup[0], hostId: 'unknown' }, { ...settings.cleanup[0], provider: 'terminal' }, { ...settings.cleanup[0], enabled: 'yes' }]) assert.throws(() => validateSettings({ ...settings, cleanup: [policy] }));
    assert.throws(() => validateSettings({ ...settings, cleanup: [settings.cleanup[0], settings.cleanup[0]] }));
    assert.equal(validateSettings({ ...settings, cleanup: [{ hostId: 'default', provider: 'antigravity', enabled: true, days: 30 }] }).cleanup[0].enabled, true);
    await cleanup.runDue(); assert.equal(remoteCalls, 0);
    store.data.settings.cleanup = [{ hostId: 'default', provider: 'antigravity', enabled: true, days: 30 }];
    await cleanup.runDue(); assert.equal(remoteCalls, 1, 'An enabled Antigravity policy dispatches a bounded preview');
    assert.ok(store.data.cleanupState.lastRuns['default/antigravity']);
    store.data.settings.cleanup = settings.cleanup;
    await assert.rejects(cleanup.preview({ hostId: 'unknown', provider: 'claude', days: 30 }), /Unknown host/);
    await assert.rejects(cleanup.preview({ hostId: 'default', provider: 'terminal', days: 30 }), /provider/);
    const request = { hostId: 'default', provider: 'claude', days: 30 };
    store.setSessionPinned(key, true);
    let preview = await cleanup.preview(request);
    assert.equal(preview.items[0].eligible, false);
    assert.match(preview.items[0].reason, /Pinned/);
    providerPinned = true; store.setSessionPinned(key, false);
    assert.equal((await cleanup.preview(request)).items[0].eligible, false);
    providerPinned = false;
    preview = await cleanup.preview(request);
    store.setSessionPinned(key, true);
    assert.equal((await cleanup.execute(preview.token, [key]))[0].status, 'excluded');
    assert.equal(deletes, 0);
    await assert.rejects(cleanup.execute(preview.token, [key]), /expired/);
    preview = await cleanup.preview({ ...request, ids: [id], allowPinned: true });
    assert.equal(preview.items[0].eligible, true);
    store.setSessionPinned(key, false);
    activity = new Date().toISOString();
    assert.equal((await cleanup.preview(request)).items[0].eligible, false);
    activity = null;
    assert.equal((await cleanup.preview(request)).items[0].eligible, false);
    activity = '2020-01-01T00:00:00Z';
    const release = cleanup.beginLaunch('default');
    await assert.rejects(cleanup.preview(request), /launches/); release();
    preview = await cleanup.preview(request);
    const stale = { tabs: [key], selectedKey: key, splitKey: null, metadata: { [key]: { pinned: false, project: 'Keep unrelated notes', notes: 'Fixture' }, 'default/claude:unrelated': { pinned: true, project: 'Keep', notes: 'Keep me' } } };
    store.save('workspace', stale);
    let deletedEvent;
    events.on('sessions:deleted', (keys) => { deletedEvent = keys; });
    let resolveDelete;
    pauseDelete = new Promise((resolve) => { resolveDelete = resolve; });
    const deletion = cleanup.execute(preview.token, [key]);
    assert.equal(cleanup.isDeleting(key), true);
    assert.equal(new Store(directory).data.cleanupState.results[0].status, 'unknown', 'An in-flight deletion must be recoverable after a crash');
    assert.throws(() => cleanup.beginLaunch('default'), /cleanup/);
    resolveDelete(); pauseDelete = null;
    assert.equal((await deletion)[0].status, 'deleted');
    assert.equal(store.data.cleanupState.results.filter((item) => item.key === key).length, 2); // Prior pinned exclusion and final deletion, with no stale pending record.
    assert.deepEqual(deletedEvent, [key]);
    store.saveWorkspace(stale);
    assert.equal(store.data.workspace.metadata[key], undefined);
    assert.deepEqual(store.data.workspace.tabs, []);
    assert.equal(store.data.workspace.metadata['default/claude:unrelated'].notes, 'Keep me');
    assert.ok(new Store(directory).data.deletedSessions.includes(key));
    sessions = [{ key, id, title: 'Fixture', hostId: 'default', provider: 'claude', kind: 'conversation', updatedAt: activity }];
    outcome = 'unknown';
    preview = await cleanup.preview(request);
    const previousDeletes = deletes;
    assert.equal((await cleanup.execute(preview.token, [key]))[0].status, 'unknown');
    await assert.rejects(cleanup.execute(preview.token, [key]), /expired/);
    assert.equal(deletes, previousDeletes + 1);
    store.save('settings', validateSettings({ ...settings, cleanup: [{ ...settings.cleanup[0], enabled: true }] }));
    rejectPreview = true;
    const previousCalls = remoteCalls;
    await cleanup.runDue();
    assert.equal(remoteCalls, previousCalls + 1);
    await createCleanup({ ...options, store: new Store(directory) }).runDue();
    assert.equal(remoteCalls, previousCalls + 1, 'Restart must not repeat the same daily attempt');
    assert.equal(new Store(directory).data.settings.cleanup[0].enabled, true);
    console.log('PASS cleanup policy validation, opt-in scheduling, persisted daily catch-up, pinned/native-pinned exclusions, activity cutoffs, launch coordination, consumed previews, unknown outcomes, deletion events, and stale-save tombstones');
  } finally { fs.rmSync(directory, { recursive: true, force: true }); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
