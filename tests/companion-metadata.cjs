const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createService } = require('../electron/service.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'agentc2-metadata-'));
const service = createService({ directory, home: os.homedir() });
const key = 'default/tmux:hq-123456789abc';
(async () => { try {
  service.store.save('workspace', { ...service.store.data.workspace, tabs: [key], selectedKey: key, metadata: { [key]: { pinned: true, project: 'Before', notes: 'Keep' } } });
  const before = service.store.data.workspace;
  assert.equal(typeof service.updateMetadata, 'function', 'Companion needs a scoped metadata update');
  assert.deepEqual(service.updateMetadata(key, { project: 'After' }), { pinned: true, project: 'After', notes: 'Keep' });
  assert.deepEqual(service.store.data.workspace.tabs, before.tabs);
  assert.equal(service.store.data.workspace.selectedKey, key);
  assert.equal(service.updateMetadata(key, { notes: 'Phone notes' }).notes, 'Phone notes');
  const stale = structuredClone(before);
  stale.metadata[key].notes = 'Old desktop snapshot';
  service.saveWorkspace(stale);
  assert.equal(service.store.data.workspace.metadata[key].notes, 'Phone notes', 'Desktop navigation must not overwrite phone notes');
  for (const patch of [null, [], { pinned: false }, { notes: 10 }, { project: 'a'.repeat(101) }, { notes: 'a'.repeat(20001) }, { notes: '\0' }]) assert.throws(() => service.updateMetadata(key, patch), /Invalid/);
  assert.throws(() => service.updateMetadata('default/tmux:unknown', { notes: 'bad' }), /unavailable/);
  assert.throws(() => service.updateMetadata(null, {}), /Invalid/);
  service.store.data.deletedSessions.push(key);
  assert.throws(() => service.updateMetadata(key, {notes:'stale edit'}), /unavailable/);
  service.store.data.deletedSessions = [];
  service.store.data.settings.hosts = [];
  await assert.rejects(service.deleteSession({ id: 'web:paired', admin: true }, key), /Reconnect/);
  await assert.rejects(service.deleteSession({ id: 'web:untrusted' }, key), /Invalid/);
  console.log('PASS phone metadata edits preserve workspace navigation and validate fields');
} finally { fs.rmSync(directory, { recursive: true, force: true }); } })().catch((error) => { console.error(error); process.exitCode = 1; });
