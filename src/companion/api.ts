import { readPhoneClipboard, writePhoneClipboard } from './clipboard';
import type { AgentHQApi, CompanionState } from '../types';
import type { CompanionClient } from './client';

/** Share typed workflow components without exposing a desktop IPC bridge. */
export function createCompanionApi(client: Pick<CompanionClient, 'request' | 'on'>): AgentHQApi {
  return {
    platform: 'android',
    peerSyncStatus: () => client.request('peer-sync:status'),
    savePeerSync: (input) => client.request('peer-sync:save', input),
    issuePeerPairing: () => client.request('peer-sync:pair'),
    connectPeer: (input) => client.request('peer-sync:connect', input),
    revokePeer: (id) => client.request('peer-sync:revoke', id),
    pullPeerTabs: (id) => client.request('peer-sync:pull-tabs', id),
    checkForUpdates: () => client.request('updates:check'),
    updateState: () => client.request('updates:state'),
    downloadUpdate: () => client.request('updates:download'),
    installUpdate: () => client.request('updates:install'),
    overwatchWindowState: () => client.request('overwatch:state'),
    undockOverwatch: () => client.request('overwatch:undock'),
    dockOverwatch: () => client.request('overwatch:dock'),
    selectOverwatchUnit: (key) => client.request('overwatch:select', key),
    githubRequest: (input) => client.request('github:request', input),
    listSpecops: () => client.request('specops:list'),
    specopsDefinition: () => client.request('specops:definition'),
    configureSpecops: (yaml) => client.request('specops:configure', yaml),
    launchSpecops: (input) => client.request('specops:launch', input),
    controlSpecops: (id, action) => client.request('specops:control', id, action),
    centcomState: () => client.request('centcom:state'),
    configureCentcom: (config) => client.request('centcom:configure', config),
    startCentcom: (prompt) => client.request('centcom:start', prompt),
    submitCentcom: (text) => client.request('centcom:submit', text),
    interruptCentcom: () => client.request('centcom:interrupt'),
    pauseCentcom: (paused) => client.request('centcom:pause', paused),
    resetCentcomSession: () => client.request('centcom:reset'),
    decideCentcomDirective: (id, decision) => client.request('centcom:decide-directive', id, decision),
    decideAllCentcomDirectives: (decision) => client.request('centcom:decide-all-directives', decision),
    applyCentcomAutomation: (id, decision) => client.request('centcom:apply-automation', id, decision),
    renameSession: (key, title) => client.request('session:rename', key, title),
    onPeerSyncStatus: (callback) => client.on('peer-sync:status', (value) => callback(value as Parameters<typeof callback>[0])),
    onPeerSyncApplied: (callback) => client.on('peer-sync:applied', (value) => callback(value as Parameters<typeof callback>[0])),
    onUpdateState: (callback) => client.on('updates:state', (value) => callback(value as Parameters<typeof callback>[0])),
    onOverwatchWindowState: (callback) => client.on('overwatch:window-state', (value) => callback(value as Parameters<typeof callback>[0])),
    onOverwatchSelect: (callback) => client.on('overwatch:selected', (value) => callback(value as Parameters<typeof callback>[0])),
    onOverwatchWorkspace: (callback) => client.on('overwatch:workspace', (value) => callback(value as Parameters<typeof callback>[0])),
    onCentcomState: (callback) => client.on('centcom:updated', (value) => callback(value as Parameters<typeof callback>[0])),
    getState: async () => { const state = await client.request<CompanionState>('state:get'); return { settings: state.settings, attention: state.attention, workspace: { tabs: [], selectedKey: null, splitKey: null, metadata: state.metadata } }; },
    saveSettings: (settings) => client.request('settings:save', settings),
    previewOpOrder: (order) => client.request('oporder:preview', order),
    enrollOpOrder: (order, revision) => client.request('oporder:enroll', order, revision),
    previewSitrep: (input) => client.request('sitrep:preview', input),
    launchSitrep: (input) => client.request('sitrep:launch', input),
    listExercises: () => client.request('exercise:list'),
    exerciseCapabilities: (hostId) => client.request('exercise:capabilities', hostId),
    createExercise: (input) => client.request('exercise:create', input),
    retryExercise: (id) => client.request('exercise:retry', id),
    cancelExercise: (id) => client.request('exercise:cancel', id),
    markExerciseComplete: (id, contestantId) => client.request('exercise:complete', id, contestantId),
    inspectExercise: (id, contestantId, verify) => client.request('exercise:inspect', id, contestantId, verify),
    previewExercisePromotion: (id, contestantId) => client.request('exercise:preview', id, contestantId),
    promoteExercise: (id, contestantId, revision) => client.request('exercise:promote', id, contestantId, revision),
    listFlashTraffic: () => client.request('flash:list'),
    decideFlashTraffic: (input) => client.request('flash:decide', input),
    interruptFaults: () => client.request('fault:interrupt-all'),
    resetFault: (key) => client.request('fault:reset', key),
    updateSessionMetadata: (key, patch) => client.request('metadata:update', key, patch),
    onSharedState: (callback) => client.on('state:updated', (value) => callback(value as CompanionState)),
    setSessionPinned: (key, pinned) => client.request('session:pin', key, pinned),
    previewCleanup: (input) => client.request('cleanup:preview', input),
    executeCleanup: (token, keys) => client.request('cleanup:execute', token, keys),
    cleanupState: () => client.request('cleanup:state'),
    terminalPreviews: (keys) => client.request('terminal:previews', keys),
    searchHistory: (query, keys) => client.request('terminal:search', query, keys),
    acknowledge: (id) => client.request('attention:ack', id),
    inventory: () => client.request('inventory'),
    health: () => client.request('health'),
    create: (input) => client.request('create', input),
    chatCapabilities: (hostId) => client.request('chat:capabilities', hostId),
    openChat: (id, hostId) => client.request('chat:open', id, hostId),
    readyChat: (id, after) => client.request('chat:ready', id, after),
    chatHistory: (id, after, limit) => client.request('chat:history', id, after, limit),
    takeChat: (id) => client.request('chat:take', id),
    submitChat: (id, command) => client.request('chat:submit', id, command),
    chatReceipt: (id, commandId) => client.request('chat:receipt', id, commandId),
    pruneChat: (id) => client.request('chat:prune', id),
    closeChat: (id) => client.request('chat:close', id),
    listWorktrees: (hostId) => client.request('worktrees:list', hostId),
    archiveWorktree: (hostId, operationId) => client.request('worktrees:archive', hostId, operationId),
    diffFiles: (input) => client.request('diff:files', input),
    diffDetail: (input) => client.request('diff:detail', input),
    diffHunk: (input) => client.request('diff:hunk', input),
    interrupt: (name, hostId) => client.request('interrupt', name, hostId),
    stop: (name, hostId) => client.request('stop', name, hostId),
    deleteSession: (key) => client.request('session:delete', key),
    openTerminal: (name, cols, rows, hostId) => client.request('terminal:open', name, cols, rows, hostId),
    terminalHistory: (id) => client.request('terminal:history', id),
    readyTerminal: (id) => client.request('terminal:ready', id),
    terminalState: (id) => client.request('terminal:state', id),
    takeTerminal: (id) => client.request('terminal:take', id),
    remoteStatus: () => client.request('remote:status'),
    saveRemote: (input) => client.request('remote:save', input),
    pairRemote: () => client.request('remote:pair'),
    revokeRemote: (id) => client.request('remote:revoke', id),
    tailscaleStatus: () => client.request('remote:tailscale'),
    writeTerminal: (id, data) => client.request('terminal:write', id, data),
    resizeTerminal: (id, cols, rows) => client.request('terminal:resize', id, cols, rows),
    closeTerminal: (id) => client.request('terminal:close', id),
    scrollTerminal: (id, direction, lines) => client.request('terminal:scroll', id, direction, lines),
    devUrls: (sessionKey) => client.request('tunnel:list', sessionKey),
    openDevUrl: (id, url) => client.request('tunnel:open', id, url),
    // Selection/layout belong to this phone; shared notes use metadata:update.
    saveWorkspace: async (workspace) => workspace,
    readClipboard: () => readPhoneClipboard(),
    readClipboardForTerminal: async (_id) => ({ kind: 'text', text: await readPhoneClipboard() }),
    writeClipboard: (text) => writePhoneClipboard(text),
    terminalMenu: async (_hasSelection) => null,
    onSessionsDeleted: (callback) => client.on('sessions:deleted', (value) => callback(value as string[])),
    onSessionPinned: (callback) => client.on('session:pinned', (value) => { const item = value as { key: string; pinned: boolean }; callback(item.key, item.pinned); }),
    onInventory: (callback) => client.on('inventory:updated', (value) => callback(value as Parameters<typeof callback>[0])),
    onHealth: (callback) => client.on('health:updated', (value) => callback(value as Parameters<typeof callback>[0])),
    onAttentionOpen: (callback) => client.on('attention:open', (value) => callback(value as string)),
    onChatEvents: (callback) => client.on('chat:events', (value) => callback(value as Parameters<typeof callback>[0])),
    onChatState: (callback) => client.on('chat:state', (value) => callback(value as Parameters<typeof callback>[0])),
    onRemoteStatus: (callback) => client.on('remote:updated', (value) => callback(value as Parameters<typeof callback>[0])),
    onTerminalState: (callback) => client.on('terminal:state', (value) => callback(value as Parameters<typeof callback>[0])),
    onTerminalData: (callback) => client.on('terminal:data', (value) => { const item = value as { id: string; data: string; sequence: number }; callback(item.id, item.data, item.sequence); }),
    onTerminalExit: (callback) => client.on('terminal:exit', (value) => { const item = value as { id: string; code: number }; callback(item.id, item.code); }),
    onDevUrls: (callback) => client.on('tunnel:updated', (value) => { const item = value as { sessionKey: string; urls: Parameters<typeof callback>[1] }; callback(item.sessionKey, item.urls); }),
  };
}
